package install

// hostsandbox.go carries the three Landlock syscalls to a device that is
// already installed (Task 49).
//
// The unit this package renders hardens the agent with
// `SystemCallFilter=@system-service`, and systemd's @system-service set does
// not include @sandbox — landlock_create_ruleset, landlock_add_rule and
// landlock_restrict_self. With `SystemCallErrorNumber=EPERM` beside it, the
// agent's own attempt to *build* a sandbox therefore failed with EPERM on
// every device the installer has ever produced.
//
// That cost nothing until the hub began asking a device that serves more than
// one project to keep a host payload to its own project (Task 20500,
// Spec.ConfineToProject): the agent builds that confinement with Landlock,
// could not, and refused every such payload — so no project could be started
// on the device at all, with the Landlock EPERM three error wrappings down.
// sgx is the device that made this necessary, as it was for the packet filter.
//
// The grant is in the unit from this release on (systemd.go). A device
// installed before it keeps the unit it has — an upgrade cannot honestly
// re-render one, see upgrade.go — so the grant reaches it the way the packet
// filter's does, as a drop-in beside the unit written by `--upgrade`.
//
// Unlike the packet filter it needs no flag and is written whenever it is
// missing. CAP_NET_ADMIN widens what a fleet device may do, which is not
// something to do as a side effect of replacing a binary; these three calls
// can only take rights away from what the agent starts. Withholding them does
// not make the device safer — it makes it refuse the confined payloads, and
// leaves the unconfined ones unconfined.

import (
	"path/filepath"
	"slices"
)

// landlockSyscalls are the calls a Landlock ruleset is built with, as systemd
// names them in @sandbox. Named here and used by both the unit and the
// drop-in, so the two cannot drift and planHostSandbox can recognise a unit
// that already carries the grant.
const landlockSyscalls = "landlock_create_ruleset landlock_add_rule landlock_restrict_self"

// hostSandboxDropInName is the drop-in that grants them on a device whose unit
// predates the grant.
//
// Numbered to sort after the packet-filter drop-in and before the channel one
// and override.conf, the name `systemctl edit` uses: an operator's own drop-in
// is read last and so still has the final word.
const hostSandboxDropInName = "11-host-sandbox.conf"

// HostSandboxDropInPath is where the Landlock grant is written.
func (s Spec) HostSandboxDropInPath() string {
	return filepath.Join(s.DropInDir(), hostSandboxDropInName)
}

// hostSandboxDirective is the whole grant: one additional allow-list for
// systemd to merge into the unit's own. Merged rather than restated, like the
// packet filter's three, so the drop-in means the same thing laid over a unit
// rendered by any release.
const hostSandboxDirective = "SystemCallFilter=" + landlockSyscalls

// HostSandboxDropIn renders the drop-in that lets the agent build a Landlock
// sandbox, so it can keep a host payload to its own project.
func HostSandboxDropIn(s Spec) string {
	return "# " + hostSandboxDropInName + " — generated by `cloop executor agent install`.\n" +
		"#\n" +
		"# Lets " + s.UnitFileName() + " keep a host payload to its own\n" +
		"# project's directory, which it does with Landlock (and no_new_privs). The\n" +
		"# unit's SystemCallFilter=@system-service does not cover the three calls a\n" +
		"# Landlock ruleset is built with — they are systemd's @sandbox set — so on a\n" +
		"# unit rendered before cloop granted them the kernel answered EPERM and the\n" +
		"# agent refused every payload the hub asked it to confine.\n" +
		"#\n" +
		"# This is not a relaxation: these calls only ever take rights away from what\n" +
		"# the agent starts. Units rendered from now on carry the grant themselves,\n" +
		"# and a full re-install removes this file.\n" +
		"\n" +
		"[Service]\n" +
		"# the three calls that build a Landlock ruleset, on top of the unit's own set\n" +
		hostSandboxDirective + "\n"
}

// unitGrantsLandlock reports whether a unit file's directives already allow the
// Landlock calls: the form systemd.go renders from this release on.
//
// An operator who granted them under another spelling (@sandbox, or their own
// drop-in) is not recognised here, and gets this drop-in as well. Two
// allow-lists for the same calls merge to the same set, so that is harmless.
func unitGrantsLandlock(unit string) bool {
	return slices.Contains(unitDirectives(unit), hostSandboxDirective)
}

// planHostSandbox decides what an upgrade does about the grant. It returns nil
// when the device already has it.
func (in *Installer) planHostSandbox(s Spec, out Output) (*dropInChange, error) {
	if out != OutputSystemd {
		// Only a systemd unit filters syscalls. The init script does not, and
		// a containerised agent is held by its engine's seccomp profile,
		// which this installer does not write.
		return nil, nil
	}
	unit, _, err := in.fileState(s.UnitPath())
	if err != nil {
		return nil, err
	}
	if unitGrantsLandlock(string(unit)) {
		return nil, nil
	}
	current, exists, err := in.fileState(s.HostSandboxDropInPath())
	if err != nil {
		return nil, err
	}
	if exists && slices.Contains(unitDirectives(string(current)), hostSandboxDirective) {
		// Already granted by this drop-in; a prose change is not worth a
		// restart of a device that is working.
		return nil, nil
	}
	return &dropInChange{
		kind: changeHostSandbox, path: s.HostSandboxDropInPath(),
		next: HostSandboxDropIn(s), previous: current, existed: exists,
		grantedAfter: true,
	}, nil
}

// describeHostSandbox says what the change did, or with dryRun would do.
func (c *dropInChange) describeHostSandbox(dryRun bool) string {
	if dryRun {
		return "would write " + c.path + ", letting the agent confine a host payload to its own project"
	}
	verb := "wrote "
	if c.existed {
		verb = "rewrote "
	}
	return verb + c.path + ": the agent may build a Landlock sandbox, so it can keep a host payload " +
		"to its own project"
}
