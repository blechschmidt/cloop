package secretbroker

import (
	"strings"

	"github.com/blechschmidt/cloop/pkg/forgehost"
)

// GitHub's canonical host: where a github_pat with no recorded host, and an
// App on the public API, is released. A grant's own host is the material's
// githubHost (forgehost.go), which a helper releases its token for and for no
// other host — not a look-alike that a workload's /etc/hosts or proxy points
// elsewhere, and not github.com for a GitHub Enterprise Server token.
const githubHost = forgehost.GitHub

// credentialHelperName is the file the generated helper is written to inside
// the lease's tmpfs directory.
const credentialHelperName = "git-credential-cloop"

// tokenFileName holds the raw token, read by the helper at use time. Keeping
// it out of the script body matters: a script is the sort of thing that ends
// up in a `set -x` trace or a debug dump of the lease directory, and a token
// baked into its text would go with it.
const tokenFileName = "github-token"

// gitconfigName is the git configuration that installs the helper.
const gitconfigName = "gitconfig"

// proxyCredentialName holds the git proxy session credential in guarded
// delivery. Like tokenFileName it is kept out of the helper script's body, and
// for the same reason — but what it holds is a session token that is worth
// nothing off the proxy, rather than the PAT itself.
const proxyCredentialName = "git-proxy-credential"

// buildGitCredentialHelper generates a POSIX sh credential helper that
// releases the token only for repositories inside the allowlist.
//
// Why a script at all: GitHub offers no way to narrow an already-issued PAT,
// so "this token may only touch org/*" cannot be enforced by reshaping the
// credential the way a kubeconfig can. The next best enforcement point is
// the moment git asks for it. Git's credential protocol supplies the
// repository path when credential.useHttpPath is on, so the helper can
// answer for org/tool and stay silent for someone-else/private — and a
// workload that never receives the token for a repository cannot use it
// there, regardless of what it intended.
//
// Injection safety: every pattern reaching this function has already passed
// validatePattern, whose charset excludes quotes, backticks, dollar signs,
// backslashes, newlines, and semicolons. We re-check here anyway rather than
// trusting that the database we read from was written by a version of this
// code with that check in it.
//
// Matching parity with Constraints.AllowsRepo is deliberate and load-bearing:
// the helper first rejects any path that is not exactly owner/name, which
// makes shell `case` globbing — where "*" happily crosses "/" — agree with
// path.Match, where it does not. Without that guard "org/*" would mean two
// different things in the two matchers, and the shell's would be the wider.
func buildGitCredentialHelper(patterns []string) (string, error) {
	return buildGitCredentialHelperFor(patterns, tokenFileName, githubHost)
}

// buildGitCredentialHelperFor is buildGitCredentialHelper reading the token
// from tokenFile and releasing it for host — the forge host the grant's token
// is good against (Task 20423) — so several GitHub grants can share one lease
// directory, each helper releasing its own token to its own host
// (githubmulti.go).
func buildGitCredentialHelperFor(patterns []string, tokenFile, host string) (string, error) {
	cases, err := repoFilterCases(patterns)
	if err != nil {
		return "", err
	}
	if !validLeaseFileToken(tokenFile) {
		return "", wrapf(ErrInvalidSecret, "unsafe credential file name %q", tokenFile)
	}
	host, err = helperHost(host)
	if err != nil {
		return "", err
	}

	var b strings.Builder
	b.WriteString("#!/bin/sh\n")
	b.WriteString("# Generated by cloop secretbroker. Releases a GitHub token only for\n")
	b.WriteString("# repositories inside the grant's allowlist. Do not edit.\n")
	b.WriteString("set -u\n")
	b.WriteString("[ \"${1:-}\" = get ] || exit 0\n")
	b.WriteString("dir=$(dirname \"$0\")\n")
	b.WriteString("proto=; host=; reqpath=\n")
	// Read git's key=value request from stdin. An unrecognised key is
	// ignored, which is what the credential protocol requires.
	b.WriteString("while IFS='=' read -r key value; do\n")
	b.WriteString("  case \"$key\" in\n")
	b.WriteString("    protocol) proto=$value ;;\n")
	b.WriteString("    host) host=$value ;;\n")
	b.WriteString("    path) reqpath=$value ;;\n")
	b.WriteString("  esac\n")
	b.WriteString("done\n")
	// Only https to the grant's own host. Anything else gets silence.
	b.WriteString("[ \"$proto\" = https ] || exit 0\n")
	writeHostFilter(&b, host)
	writeRepoFilter(&b, cases)
	b.WriteString("[ -r \"$dir/" + tokenFile + "\" ] || exit 0\n")
	b.WriteString("printf 'username=x-access-token\\n'\n")
	b.WriteString("printf 'password=%s\\n' \"$(cat \"$dir/" + tokenFile + "\")\"\n")
	return b.String(), nil
}

// helperHost canonicalises the host a generated helper answers for, and
// refuses one that could not appear in its body unquoted. The canonical
// charset is already narrower than that; this is the check at the sink.
func helperHost(host string) (string, error) {
	c, err := forgehost.Canonical(host)
	if err != nil {
		return "", wrapf(ErrInvalidSecret, "credential helper host %q: %v", host, err)
	}
	if err := validateShellSafeHost(c); err != nil {
		return "", wrapf(ErrInvalidSecret, "credential helper host: %v", err)
	}
	return c, nil
}

// writeHostFilter renders the helper lines that stay silent unless git's
// request names host, which must already be canonical and shell-safe.
//
// git reports the host as the URL spelled it, so the two spellings forgehost
// folds that a shell can fold too are folded here — letter case, and one
// trailing dot. Anything else it folds (a default port spelled out, a
// Unicode spelling) gets silence: the safe direction, since a non-match
// releases nothing.
func writeHostFilter(b *strings.Builder, host string) {
	b.WriteString("host=$(printf '%s' \"$host\" | tr 'ABCDEFGHIJKLMNOPQRSTUVWXYZ' 'abcdefghijklmnopqrstuvwxyz' 2>/dev/null || printf '%s' \"$host\")\n")
	b.WriteString("host=${host%.}\n")
	// Single-quoted: the charset has no quote in it, and a bracketed IPv6
	// literal left bare would be a glob the shell could expand.
	b.WriteString("[ \"$host\" = '" + host + "' ] || exit 0\n")
}

// repoFilterCases validates an allowlist and renders it as the alternatives of
// a shell `case` pattern, lowercased, with a wildcard allowlist collapsed to
// the one pattern the single-slash guard in writeRepoFilter still constrains.
func repoFilterCases(patterns []string) ([]string, error) {
	cases := make([]string, 0, len(patterns))
	allowAll := false
	for _, p := range patterns {
		if err := validatePattern("repos", p); err != nil {
			return nil, err
		}
		lowered := strings.ToLower(strings.TrimSuffix(strings.Trim(p, "/"), ".git"))
		if lowered == "*" || lowered == "*/*" {
			allowAll = true
		}
		cases = append(cases, lowered)
	}
	if allowAll {
		// Collapse to a single pattern that the single-slash guard above
		// still constrains to owner/name.
		cases = []string{"*/*"}
	}
	return cases, nil
}

// writeRepoFilter renders the helper lines that stay silent unless git's
// request names a repository inside cases. It reads $reqpath, which the helper
// has already parsed from git's request.
func writeRepoFilter(b *strings.Builder, cases []string) {
	writeRepoFilterUnder(b, cases, "")
}

// writeRepoFilterUnder is writeRepoFilter for repositories beneath prefix: a
// request path outside it gets silence, and the prefix is stripped before the
// owner/name checks. prefix is a proxy route path (githubguarded.go), already
// validated to plain lowercase segments; it is checked again here because
// this is where it meets the shell.
func writeRepoFilterUnder(b *strings.Builder, cases []string, prefix string) {
	for _, c := range prefix {
		switch {
		case c >= 'a' && c <= 'z', c >= '0' && c <= '9':
		case c == '.' || c == '-' || c == '_' || c == ':' || c == '/':
		default:
			// Unreachable through newProxyRoute. A prefix that cannot be
			// rendered safely matches nothing.
			b.WriteString("exit 0\n")
			return
		}
	}
	b.WriteString("[ -n \"$reqpath\" ] || exit 0\n")
	// Normalise: strip a leading slash and a .git suffix, then lowercase.
	// If tr is missing the comparison stays cased and simply fails to
	// match — the safe direction, since a non-match releases nothing.
	b.WriteString("repo=${reqpath#/}\n")
	b.WriteString("repo=${repo%.git}\n")
	b.WriteString("repo=$(printf '%s' \"$repo\" | tr 'ABCDEFGHIJKLMNOPQRSTUVWXYZ' 'abcdefghijklmnopqrstuvwxyz' 2>/dev/null || printf '%s' \"$repo\")\n")
	if prefix = strings.Trim(prefix, "/"); prefix != "" {
		// Beneath this host's route, or silence: a request on another
		// host's route — or on github.com's, at the base — is not this
		// grant's to answer.
		b.WriteString("case \"$repo\" in\n")
		b.WriteString("  '" + prefix + "/'*) repo=${repo#'" + prefix + "/'} ;;\n")
		b.WriteString("  *) exit 0 ;;\n")
		b.WriteString("esac\n")
	}
	// Exactly one slash: this is what makes shell globbing agree with
	// path.Match's non-separator-crossing "*".
	b.WriteString("case \"$repo\" in\n")
	b.WriteString("  */*/*) exit 0 ;;\n")
	b.WriteString("  */*) ;;\n")
	b.WriteString("  *) exit 0 ;;\n")
	b.WriteString("esac\n")
	b.WriteString("case \"$repo\" in\n")
	b.WriteString("  " + strings.Join(cases, "|") + ") ;;\n")
	b.WriteString("  *) exit 0 ;;\n")
	b.WriteString("esac\n")
}

// validLeaseFileToken reports whether name is safe to write into a generated
// shell script and gitconfig as a bare lease-directory file name.
func validLeaseFileToken(name string) bool {
	if name == "" || len(name) > 64 {
		return false
	}
	for _, r := range name {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '-', r == '_', r == '.':
		default:
			return false
		}
	}
	return name != "." && name != ".."
}

// buildGitConfig returns a git configuration file that installs the helper
// and turns on useHttpPath, without which git would not tell the helper
// which repository it is authenticating for — and the allowlist would have
// nothing to match against.
//
// The helper is referenced through $CLOOP_LEASE_DIR rather than an absolute
// path because the config is built before the lease directory exists, and
// because a remote executor materialises the lease at a path the control
// plane never learns. The "!" prefix is what makes git run the value through
// a shell, which is what expands the variable; git appends the operation, so
// the script still receives "get" as $1.
//
// It is delivered via GIT_CONFIG_GLOBAL so it applies to the workload
// without touching any real ~/.gitconfig, and evaporates with the lease.
func buildGitConfig() string {
	var b strings.Builder
	b.WriteString("# Generated by cloop secretbroker for the lifetime of one lease.\n")
	b.WriteString("[credential]\n")
	b.WriteString("\tuseHttpPath = true\n")
	b.WriteString("\thelper = !\"$CLOOP_LEASE_DIR/" + credentialHelperName + "\"\n")
	return b.String()
}

// GitHubToken returns the raw token a GitHub material carries, and whether it
// carries one at all.
//
// It exists because workspace provisioning (pkg/executor/gitcreds) needs the
// token as an HTTP basic password, and the two paths that already deliver it —
// the credential-helper script and the bare GITHUB_TOKEN env var — are both
// wrong for that use. The helper needs a shell and a materialised lease
// directory, which is exactly the disk write a sandbox fetch must avoid; and
// GITHUB_TOKEN is only exported for an unrestricted "*" grant, so relying on it
// would make narrow grants silently unable to clone.
//
// The returned string is the caller's to handle carefully — it is a
// credential, and nothing here can stop it being logged.
//
// The dedicated field is consulted first and the Files scan is the fallback.
// The two used to be one thing, and separating them is what lets a guarded
// delivery withhold the token from the sandbox without also withholding it
// from the hub: under GitGuard there is no token file to find, but the hub's
// own workspace provisioning still needs the credential to hand to the proxy.
// The fallback keeps Materials built by older paths — and by tests that
// construct one directly — answering as they did.
func (m Material) GitHubToken() (string, bool) {
	switch m.Kind {
	case KindGitHubPAT, KindGitHubApp:
	default:
		return "", false
	}
	if t := strings.TrimSpace(m.githubToken); t != "" {
		return t, true
	}
	for _, f := range m.Files {
		if f.Name != tokenFileName {
			continue
		}
		token := strings.TrimSpace(string(f.Content))
		if token == "" {
			return "", false
		}
		return token, true
	}
	return "", false
}

// GitHubUsername is the basic-auth username GitHub expects alongside a PAT.
// GitHub ignores the value for a PAT but requires a non-empty one, and
// "x-access-token" is the name its own tooling uses.
const GitHubUsername = "x-access-token"

// allowsAllRepos reports whether the allowlist is an unrestricted wildcard.
//
// This gates whether a bare GITHUB_TOKEN environment variable is exported.
// An env var is unscoped by construction — every tool in the workload reads
// it and uses it against any repository — so it is only honest to export one
// when the operator has explicitly said "all repositories". For a narrower
// grant the credential helper is the only delivery path, which is the whole
// difference between an enforced allowlist and a documented one.
func allowsAllRepos(patterns []string) bool {
	for _, p := range patterns {
		switch strings.ToLower(strings.TrimSpace(p)) {
		case "*", "*/*":
			return true
		}
	}
	return false
}
